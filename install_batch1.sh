# if it lists only those rows, ./fx.sh repair --apply  (marks them void; they leave the statistics).
set -u
REPO="${REPO:-$HOME/fx-agents}"; BR="${BR:-main}"; ORIGIN="${ORIGIN:-origin}"; DRY="${DRY:-0}"
HOOKS="${HOOKS:-$HOME/apply_my_hooks.py}"
AU="${AU:-$HOME/auto_update.sh}"
LOG="${LOG:-$HOME/install_batch1.log}"; LOCK="${LOCK:-/tmp/fx-auto-update.lock}"; TEST_TIMEOUT="${TEST_TIMEOUT:-2400}"
DC="docker compose"
exec > >(tee -a "$LOG") 2>&1
say() { echo "$(date '+%F %T') $*"; }
notify() {
  local t; t=$(grep -E '^NTFY_TOPIC=' "$REPO/.env" 2>/dev/null | tail -1 | cut -d= -f2- | tr -d "\"' ")
  [ -n "$t" ] && curl -fsS -m 15 -d "FX batch-1 install: $*" "https://ntfy.sh/$t" >/dev/null 2>&1
  say "$*"; return 0
}
die() { notify "STOPPED, nothing changed: $*"; exit 1; }
cd "$REPO" || { say "no such folder: $REPO"; exit 1; }
exec 9>"$LOCK"; flock -n 9 || die "an update is running - try again in 15 minutes"
[ "$(git rev-parse --abbrev-ref HEAD)" = "$BR" ] || die "the repo is not on $BR"
[ -z "$(git status --porcelain)" ] || die "the repo has uncommitted changes - commit or undo them first"
[ -f "$HOOKS" ] || die "$HOOKS not found"
[ -f "$AU" ] || die "$AU not found"
[ ! -e fxagents/dashboard/tfbars_ext.py ] || die "already installed (fxagents/dashboard/tfbars_ext.py exists)"
python3 - <<'PY' || die "your friend's dashboard files are not laid out as I expect (the chart hook needs new anchors) - tell me"
s = open("fxagents/dashboard/server.py", encoding="utf-8").read(); h = open("fxagents/dashboard/static/index.html", encoding="utf-8").read()
assert s.count("        return JSONResponse(insights.bars(ctx, symbol, start, end))\n") == 1, "server.py anchor"
assert h.count("</script>\n</body>") == 1, "index.html anchor"
PY
grep -q 'RETIRED = {"my_rsi_15m"}' tests/test_my_books.py || die "already installed, or tests/test_my_books.py differs from what I expect (no RETIRED = {\"my_rsi_15m\"} line)"
grep -q "^  modes:" config.yaml || die "no modes line in config.yaml"
T=$(mktemp -d); trap 'rm -rf "$T"' EXIT
