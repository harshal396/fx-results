# install_batch3.sh (Nov 5 2026) - two changes in one install:
#   (1) the Analysis page gets a "My RSI·EMA (all)" button (all your books together, working Timeframe filter, readable refusal names),
#   (2) US2000 (OANDA US2000_USD) is added as a market: watch-only for your friend's books, traded by your RSI / EMA books.
# Run:  bash ~/install_batch3.sh        Check only (changes nothing):  DRY=1 bash ~/install_batch3.sh
# Needs install_batch2.sh to be installed first (it builds on its hook lines). It replaces ~/apply_my_hooks.py (a backup is kept), adds 5 new
# files (a route, a page script and three test files), runs the hook script, updates two config tests in tests/test_my_books.py, and changes
# nothing unless ALL of these hold, in order:
#   1. you are on main with no uncommitted changes, no update is running, and the hook anchors are where they should be
#   2. the image builds and the FULL test suite passes in a throwaway container (the running bot is untouched until now)
#   3. the restarted bot answers /healthz and keeps answering 45 s later
# Any failure after step 1 puts the code (and ~/apply_my_hooks.py) back exactly as it was. Only after a healthy restart is it pushed.
set -u
REPO="${REPO:-$HOME/fx-agents}"; BR="${BR:-main}"; ORIGIN="${ORIGIN:-origin}"; DRY="${DRY:-0}"
HOOKS="${HOOKS:-$HOME/apply_my_hooks.py}"
LOG="${LOG:-$HOME/install_batch3.log}"; LOCK="${LOCK:-/tmp/fx-auto-update.lock}"; TEST_TIMEOUT="${TEST_TIMEOUT:-2400}"
DC="docker compose"
exec > >(tee -a "$LOG") 2>&1
say() { echo "$(date '+%F %T') $*"; }
notify() {
  local t; t=$(grep -E '^NTFY_TOPIC=' "$REPO/.env" 2>/dev/null | tail -1 | cut -d= -f2- | tr -d "\"' ")
  [ -n "$t" ] && curl -fsS -m 15 -d "FX batch-3 install: $*" "https://ntfy.sh/$t" >/dev/null 2>&1
  say "$*"; return 0
}
die() { notify "STOPPED, nothing changed: $*"; exit 1; }
cd "$REPO" || { say "no such folder: $REPO"; exit 1; }
exec 9>"$LOCK"; flock -n 9 || die "an update is running - try again in 15 minutes"
[ "$(git rev-parse --abbrev-ref HEAD)" = "$BR" ] || die "the repo is not on $BR"
[ -z "$(git status --porcelain)" ] || die "the repo has uncommitted changes - commit or undo them first"
[ -f "$HOOKS" ] || die "$HOOKS not found"
grep -q _install_close fxagents/dashboard/server.py || die "install_batch2.sh is not installed yet - run that one first"
[ ! -e fxagents/dashboard/my_analysis.py ] || die "already installed (fxagents/dashboard/my_analysis.py exists)"
python3 - <<'PY' || die "the hook lines or the config are not laid out as I expect (a hook needs a new anchor) - tell me"
import re
s = open("fxagents/dashboard/server.py", encoding="utf-8").read(); h = open("fxagents/dashboard/static/index.html", encoding="utf-8").read(); c = open("config.yaml", encoding="utf-8").read()
assert s.count("    _install_close(app, ctx, need, bk)\n") == 1, "server.py anchor"
assert h.count('<script src="myclose.js"></script>   <!-- Harshal: a Close now button on open trades -->\n') == 1, "index.html anchor"
assert len(re.findall(r"^    oanda: \{instrument: US30_USD[^\n]*\n", c, re.M)) == 1, "config: the US30 instrument line"
assert len(re.findall(r"^    US30: 3\.00[^\n]*\n", c, re.M)) == 1, "config: the spread table"
o = open("tests/test_oanda.py", encoding="utf-8").read()
assert o.count('    assert n == 3 * len(BASE["instruments"])                    # 3 new minutes × every symbol') == 1, "tests/test_oanda.py: the feed-count line"
PY
